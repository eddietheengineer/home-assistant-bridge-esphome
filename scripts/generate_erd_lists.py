def _get_primary_field(erd_by_id: Dict[str, Dict], paired_erd_str: str):
    """Return the first non-reserved, non-bitfield data field of the paired ERD.

    Used by number entities to extract only the primary value bytes from the
    (potentially multi-field) status ERD payload.
    Returns None if the paired ERD is unknown or has no suitable field.
    """
    if not paired_erd_str or paired_erd_str not in erd_by_id:
        return None
    status_data = erd_by_id[paired_erd_str].get('data', [])
    return next(
        (d for d in status_data
         if not _is_reserved_field(d.get('name', ''))
         and not _has_bits(d)),
        None
    )


def _number_min_max(effective_bytes: int, scale_factor: int, signed: bool):
    """Compute (min_val, max_val, step_val) for a number entity.

    *effective_bytes* is the number of bytes whose value the Home Assistant
    value_template will actually read (may differ from the full ERD data_size
    when only a slice of the payload is used).  The step equals 1/scale_factor
    so that fractional increments are correct when a scaling factor is present.

    The byte count is capped at 4 (uint32 / int32 range) so the resulting max
    value fits exactly in a JSON double (IEEE 754 doubles represent integers
    exactly up to 2^53).  Values beyond 4.3 billion are not realistic for any
    appliance sensor or control, so the cap has no practical impact.

    Returned values are Python floats; callers should round to avoid tiny
    floating-point artefacts.
    """
    # Cap at 4 bytes so results fit cleanly in a JSON float (uint32 max ≈ 4.3 B).
    capped = min(effective_bytes, 4)
    if signed:
        half = 2 ** (capped * 8 - 1)
        min_val = -half / scale_factor
        max_val = (half - 1) / scale_factor
    else:
        raw_max = (1 << (capped * 8)) - 1
        min_val = 0.0
        max_val = raw_max / scale_factor
    step_val = 1.0 / scale_factor if scale_factor > 1 else 1.0
    return min_val, max_val, step_val


def _effective_dtype(eff_bytes: int, signed: bool) -> str:
    """Return the canonical data-type string for a number entity.

    Maps (effective_bytes, signed) to one of the type names understood by the
    C++ runtime parser: ``int8``, ``int16``, ``int24``, ``int32``, ``uint8``,
    ``uint16``, ``uint24``, ``uint32``.

    Byte counts above 4 are capped at 4 (``uint32`` / ``int32``) because JSON
    ``double`` cannot exactly represent values beyond 2^53, and no real
    appliance value approaches 4 billion.
    """
    capped = min(eff_bytes, 4)  # cap: JSON double is exact up to 2^53; uint32 max (~4.3B) is well within that
    if signed:
        return {1: 'int8', 2: 'int16', 3: 'int24', 4: 'int32'}[capped]
    return {1: 'uint8', 2: 'uint16', 3: 'uint24', 4: 'uint32'}[capped]


# Lookup table for (type_min, type_max) by data-type name.
# The C++ runtime uses an identical mapping.
_DTYPE_RANGE: dict = {
    'int8':   (-128.0,        127.0),
    'int16':  (-32768.0,      32767.0),
    'int24':  (-8388608.0,    8388607.0),
    'int32':  (-2147483648.0, 2147483647.0),
    'uint8':  (0.0,           255.0),
    'uint16': (0.0,           65535.0),
    'uint24': (0.0,           16777215.0),
    'uint32': (0.0,           4294967295.0),
}


def _range_from_dtype(dtype: str, scale_factor: int = 1):
    """Return (min_val, max_val, step_val) for a given data type and scale factor.

    Mirrors the lookup table used in the C++ runtime so that Python tests can
    verify end-to-end correctness without running the embedded firmware.

    Raises ``KeyError`` for unknown type names.
    """
    if scale_factor < 1:
        scale_factor = 1
    type_min, type_max = _DTYPE_RANGE[dtype]
    min_val  = type_min / scale_factor
    max_val  = type_max / scale_factor
    step_val = 1.0 / scale_factor if scale_factor > 1 else 1.0
    return min_val, max_val, step_val


def _infer_dtype_from_jsonl_entry(obj: dict) -> str:
    """Infer the data-type string for a number entity from a JSONL object.

    Used to migrate existing JSONL files to the ``dt`` field.  The
    value_template string encodes the information originally derived from the
    ERD data type:

    * *Signedness* is detected by looking for either of the two sign-extension
      patterns that the template generators can emit for signed integer types
      (i8, i16, i32 …):
        - Old if-else form:  ``int(base=16)) - <N> if``
        - New modulo form:   ``int(base=16)) + <N>) % <N>``
    * *Effective byte count* is derived from the ``value[0:N]`` leading-slice
      notation that paired-ERD templates use; otherwise the full ``ds`` field
      is used.
    """
    data_size = int(obj.get('ds', 1))
    if data_size < 1:
        data_size = 1

    vt = obj.get('vt', '')

    # Detect signedness from either template form:
    #   Old if-else: "int(base=16)) - <N> if"
    #   New modulo:  "int(base=16)) + <N>) % <N>"
    signed = bool(
        re.search(r'int\(base=16\)\)\s*-\s*\d+\s+if', vt) or
        re.search(r'int\(base=16\)\)\s*\+\s*\d+\)\s*%\s*\d+', vt)
    )

    # Detect effective byte count from leading-slice notation.
    effective_bytes = data_size
    m = re.search(r'value\[0:(\d+)\]', vt)
    if m:
        hex_chars = int(m.group(1))
        if hex_chars >= 2 and hex_chars % 2 == 0:
            effective_bytes = hex_chars // 2

    return _effective_dtype(effective_bytes, signed)


def backfill_ha_discovery_jsonl_data_type(jsonl_dir: 'Path') -> int:
    """Migrate number entities in JSONL files from mn/mx/st to the dt field.

    Removes the old explicit ``mn``, ``mx``, and ``st`` fields from every
    number entity and replaces them with a single ``dt`` (data type) field
    (e.g. ``"uint8"``, ``"uint16"``, ``"int16"``).

    The C++ runtime then derives ``min``, ``max``, and ``step`` from ``dt``
    combined with the already-present ``sf`` (scale factor) field.

    Returns the total number of entries updated.
    """
    updated = 0
    for path in sorted(jsonl_dir.glob('*.jsonl')):
        lines_in = path.read_text(encoding='utf-8').splitlines()
        lines_out = []
        changed = False
        for line in lines_in:
            line = line.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
            except json.JSONDecodeError:
                lines_out.append(line)
                continue
            if obj.get('d') == 'number':
                had_old = any(k in obj for k in ('mn', 'mx', 'st'))
                for k in ('mn', 'mx', 'st'):
                    obj.pop(k, None)
                if 'dt' not in obj:
                    obj['dt'] = _infer_dtype_from_jsonl_entry(obj)
                    updated += 1
                    changed = True
                elif had_old:
                    changed = True
            lines_out.append(json.dumps(obj, ensure_ascii=False, separators=(',', ':')))
        if changed:
            path.write_text('\n'.join(lines_out) + '\n', encoding='utf-8')
    return updated


def _collect_ha_discovery_entries(erds: List[Dict]) -> List[Dict]:
    """Process all ERDs with ha_domain metadata and return a list of entry dicts.

    Each dict has the keys: erd_id, name, domain, unit, device_class,
    state_class, scaling_factor, data_size, paired_erd_id, pair_role,
    value_template, command_template, options_json, field_id, data_type.

    This is the single source of truth for ha-discovery data; both the C header
    generator and the JSONL generator call this function.
    """
    erd_by_id: Dict[str, Dict] = {e['id']: e for e in erds}
    ha_erds = [e for e in erds if 'ha_domain' in e]
    entries: List[Dict] = []

    def collect(erd_id_int: int, name: str, domain: str, unit: str,
                dev_cls: str, state_cls: str, scaling: int, d_size: int,
                paired_id: int, role: str, val_tmpl: str, cmd_tmpl: str,
                opts: str, field_id: str,
                data_type: str = '') -> None:
        entries.append({
            'erd_id': erd_id_int,
            'name': name,
            'domain': domain,
            'unit': unit,
            'device_class': dev_cls,
            'state_class': state_cls,
            'scaling_factor': scaling,
            'data_size': d_size,
            'paired_erd_id': paired_id,
            'pair_role': role,
            'value_template': val_tmpl,
            'command_template': cmd_tmpl,
            'options_json': opts,
            'field_id': field_id,
            'data_type': data_type,
        })

    for erd in ha_erds:
        erd_id_int = parse_erd_id(erd['id'])
        name = erd.get('name', '')
        ha_domain = erd.get('ha_domain', '')
        unit = _unit_to_ha(erd.get('unit_of_measurement') or '')
        device_class = erd.get('device_class') or ''
        state_class = erd.get('state_class') or ''
        scaling_factor = int(erd.get('scaling_factor') or 1)
        pair_role = erd.get('pair_role') or ''
        paired_erd_str = erd.get('paired_erd') or ''
        paired_erd_id = parse_erd_id(paired_erd_str) if paired_erd_str else 0
        display_name = _strip_pair_role_word(name) if pair_role else name
        erd_data = erd.get('data', [])
        data_size = get_erd_byte_size(erd_data) or 1

        classification = (
            'single'
            if ha_domain in ('select', 'number', 'button', 'switch')
            else _classify_erd_data(erd_data)
        )

        if classification == 'single':
            vt, ct, opts, dt = '', '', '', ''

            if ha_domain == 'sensor':
                if device_class == 'enum':
                    ev, fs = _get_first_enum_field_info(erd_data)
                    vt = _enum_sensor_value_template(ev, fs)
                elif data_size <= 4:
                    signed = _is_signed_type(_get_primary_data_type(erd_data))
                    vt = _compute_sensor_value_template(scaling_factor, data_size, signed)
            elif ha_domain == 'binary_sensor':
                vt = _compute_binary_sensor_value_template(data_size)
            elif ha_domain == 'switch':
                if paired_erd_str and paired_erd_str in erd_by_id:
                    s_size = get_erd_byte_size(erd_by_id[paired_erd_str].get('data', [])) or 1
                    vt = _compute_binary_sensor_value_template(s_size)
            elif ha_domain == 'select':
                ev = get_first_enum_values(erd_data)
                if ev:
                    opts, vt, ct = _select_options_and_templates(ev, data_size)
            elif ha_domain == 'number':
                pf = _get_primary_field(erd_by_id, paired_erd_str)
                if pf:
                    p_scale = int(erd_by_id[paired_erd_str].get('scaling_factor') or 1)
                    vt = _byte_subfield_value_template(pf, p_scale)
                    signed = _is_signed_type(pf.get('type', 'u8'))
                    eff_bytes = pf.get('size', 1)
                elif paired_erd_str and paired_erd_str in erd_by_id:
                    p_scale = int(erd_by_id[paired_erd_str].get('scaling_factor') or 1)
                    paired_type = _get_primary_data_type(erd_by_id[paired_erd_str].get('data', []))
                    signed = _is_signed_type(paired_type)
                    vt = _compute_sensor_value_template(p_scale, data_size, signed)
                    eff_bytes = data_size
                else:
                    signed = _is_signed_type(_get_primary_data_type(erd_data))
                    vt = _compute_sensor_value_template(scaling_factor, data_size, signed)
                    eff_bytes = data_size
                ct = _number_command_template(data_size, scaling_factor, signed)
                dt = _effective_dtype(eff_bytes, signed)
            # button: no templates

            collect(erd_id_int, display_name, ha_domain, unit, device_class,
                    state_class, scaling_factor, data_size, paired_erd_id,
                    pair_role, vt, ct, opts, '',
                    dt if ha_domain == 'number' else '')

        elif classification == 'byte_offset':
            nr_fields = _get_non_reserved_fields(erd_data)
            for idx, field in enumerate(nr_fields):
                leaf = _leaf_field_name(field.get('name', ''))
                entity_name = (leaf if leaf.lower().startswith(display_name.lower())
                               else f'{display_name} - {leaf}')
                fid = '' if idx == 0 else _field_slug(leaf)
                f_type = field.get('type', '')
                f_dev_cls = 'enum' if f_type == 'enum' else (device_class if idx == 0 else '')
                f_state_cls = state_class if idx == 0 else ''
                f_unit = _infer_unit_from_field_name(leaf, unit)
                vt = _byte_subfield_value_template(field, scaling_factor)
                collect(erd_id_int, entity_name, ha_domain, f_unit, f_dev_cls,
                        f_state_cls, scaling_factor, data_size, paired_erd_id,
                        pair_role, vt, '', '', fid)

        elif classification == 'bitfield':
            for field in _get_non_reserved_fields(erd_data):
                leaf = _leaf_field_name(field.get('name', ''))
                fid = _field_slug(leaf)
                bits_size = field.get('bits', {}).get('size', 1)
                sub_domain = 'binary_sensor' if bits_size == 1 else 'sensor'
                vt = _bitfield_sub_value_template(field)
                collect(erd_id_int, f'{display_name} - {leaf}', sub_domain, '', '',
                        '', scaling_factor, data_size, paired_erd_id, pair_role,
                        vt, '', '', fid)

        elif classification == 'mixed':
            primary = next(
                (d for d in erd_data
                 if not _has_bits(d) and not _is_reserved_field(d.get('name', ''))),
                None
            )
            if primary:
                p_type = primary.get('type', '')
                p_dev_cls = 'enum' if p_type == 'enum' else device_class
                p_vt = _byte_subfield_value_template(primary, scaling_factor)
                collect(erd_id_int, display_name, ha_domain, unit, p_dev_cls,
                        state_class, scaling_factor, data_size, paired_erd_id,
                        pair_role, p_vt, '', '', '')

            for field in [d for d in erd_data
                          if _has_bits(d) and not _is_reserved_field(d.get('name', ''))]:
                leaf = _leaf_field_name(field.get('name', ''))
                fid = _field_slug(leaf)
                bits_size = field.get('bits', {}).get('size', 1)
                sub_domain = 'binary_sensor' if bits_size == 1 else 'sensor'
                vt = _bitfield_sub_value_template(field)
                collect(erd_id_int, f'{display_name} - {leaf}', sub_domain, '', '',
                        '', scaling_factor, data_size, paired_erd_id, pair_role,
                        vt, '', '', fid)

    return entries


# Category definitions: (name, low ERD id, high ERD id)
_HA_DISCOVERY_CATEGORIES = [
    ('common',        0x0000, 0x0FFF),
    ('refrigeration', 0x1000, 0x1FFF),
    ('laundry',       0x2000, 0x2FFF),
    ('dishwasher',    0x3000, 0x3FFF),
    ('waterheater',   0x4000, 0x4FFF),
    ('range',         0x5000, 0x5FFF),
    ('airconditioning', 0x7000, 0x7FFF),
    ('waterfilter',   0x8000, 0x8FFF),
    ('smallappliance', 0x9000, 0x9FFF),
    ('energy',        0xD000, 0xDFFF),
]


def generate_ha_discovery_jsonl_by_category(erds: List[Dict]) -> Dict[str, str]:
    """Generate compact JSONL content grouped by appliance category.

    Returns a dict mapping category name → JSONL string content.
    Each JSONL line is a compact JSON object with the pre-computed ha-discovery
    fields for one entity.  Fields that equal their default value are omitted to
    reduce file size.
    """
    entries = _collect_ha_discovery_entries(erds)

    categorized: Dict[str, list] = {cat: [] for cat, _, _ in _HA_DISCOVERY_CATEGORIES}
    for entry in entries:
        eid = entry['erd_id']
        for cat, lo, hi in _HA_DISCOVERY_CATEGORIES:
            if lo <= eid <= hi:
                categorized[cat].append(entry)
                break

    result: Dict[str, str] = {}
    for cat, _, _ in _HA_DISCOVERY_CATEGORIES:
        cat_entries = categorized[cat]
        if not cat_entries:
            continue
        lines = []
        for e in cat_entries:
            obj: Dict = {
                'i': f'{e["erd_id"]:04x}',
                'n': e['name'],
                'd': e['domain'],
                'ds': e['data_size'],
            }
            # Omit fields that equal their defaults to save space
            if e['unit']:                         obj['u']  = e['unit']
            if e['device_class']:                 obj['dc'] = e['device_class']
            if e['state_class']:                  obj['sc'] = e['state_class']
            if e['scaling_factor'] != 1:          obj['sf'] = e['scaling_factor']
            if e['paired_erd_id']:                obj['p']  = f'{e["paired_erd_id"]:04x}'
            if e['pair_role']:                    obj['r']  = e['pair_role']
            if e['value_template']:               obj['vt'] = e['value_template']
            if e['command_template']:             obj['ct'] = e['command_template']
            if e['options_json']:                 obj['o']  = e['options_json']
            if e['field_id']:                     obj['fi'] = e['field_id']
            # Emit data type for number entities so the C++ runtime can derive
            # the correct min/max bounds for each HA entity.
            if e.get('data_type'):                obj['dt'] = e['data_type']
            lines.append(json.dumps(obj, ensure_ascii=False, separators=(',', ':')))
        result[cat] = '\n'.join(lines) + '\n'

    return result


def generate_ha_discovery_minimal_header(erds: List[Dict]) -> str:
    """Generate a minimal ha_discovery_config.h with only the string-ERD list.

    The full HA-discovery entity table is no longer compiled into flash.
    Instead the bridge fetches compact per-category JSONL files at runtime.
    """
    ha_erds = [e for e in erds if 'ha_domain' in e]
    string_ha_erds = [
        e for e in ha_erds
        if any(d.get('type') == 'string' for d in e.get('data', []))
    ]

    lines: List[str] = []
    lines.append('/*!')
    lines.append(' * @file')
    lines.append(' * @brief Known string-valued ERD IDs for the MQTT adapter.')
    lines.append(' *')
    lines.append(' * Full HA-discovery entity definitions are NOT stored here.')
    lines.append(' * They are fetched at runtime from compact per-category JSONL files hosted at:')
    lines.append(' *   https://raw.githubusercontent.com/joshualongenecker/'
                 'home-assistant-bridge-esphome/main/ha_discovery/')
    lines.append(' *')
    lines.append(' * Do not edit this file manually.'
                 ' Run scripts/generate_erd_lists.py to regenerate.')
    lines.append(' */')
    lines.append('')
    lines.append('#ifndef HA_DISCOVERY_CONFIG_H')
    lines.append('#define HA_DISCOVERY_CONFIG_H')
    lines.append('')
    lines.append('#include <stdint.h>')
    lines.append('')
    lines.append('// ERDs whose value is a null-terminated ASCII string.')
    lines.append('// The MQTT adapter publishes these as text rather than hex.')
    lines.append('static const uint16_t ha_string_erd_ids[] = {')
    for e in string_ha_erds:
        eid = parse_erd_id(e['id'])
        lines.append(f'  0x{eid:04x},  /* {e["name"]} */')
    lines.append('};')
    lines.append('static const uint16_t ha_string_erd_count =')
    lines.append('  (uint16_t)(sizeof(ha_string_erd_ids) / sizeof(ha_string_erd_ids[0]));')
    lines.append('')
    lines.append('#endif')
    lines.append('')

    return '\n'.join(lines)


def main():
    """Main entry point for the script."""
    # Determine paths relative to script location
    script_dir = Path(__file__).parent
    repo_root = script_dir.parent

    # -------------------------------------------------------------------------
    # Generate erd_lists.h from appliance_api_erd_definitions.json
    # -------------------------------------------------------------------------
    json_file = repo_root / 'lib' / 'public-appliance-api-documentation' / 'appliance_api_erd_definitions.json'
    output_file = repo_root / 'components' / 'geappliances_bridge' / 'erd_lists.h'

    if not json_file.exists():
        print(f"Error: Could not find {json_file}", file=sys.stderr)
        print("Make sure git submodules are initialized: git submodule update --init --recursive", file=sys.stderr)
        sys.exit(1)

    # Read and parse JSON
    print(f"Reading ERD definitions from {json_file}")
    with open(json_file, 'r') as f:
        data = json.load(f)

    erds = data.get('erds', [])
    print(f"Found {len(erds)} ERD definitions")

    # Categorize ERDs
    categories = categorize_erds(erds)

    # Print statistics
    print("\nERD counts by category:")
    for category, erd_list in categories.items():
        print(f"  {category}: {len(erd_list)}")

    # Calculate required POLLING_LIST_MAX_SIZE.
    # The polling list holds: common ERDs + energy ERDs + appliance API feature ERDs + appliance-specific ERDs.
    # Use the worst case across all appliance-specific categories.
    appliance_specific_categories = [
        'waterHeater', 'laundry', 'refrigeration', 'smallAppliance',
        'range', 'dishWasher', 'airConditioning', 'waterFilter'
    ]
    max_appliance_erds = max(len(categories[cat]) for cat in appliance_specific_categories)
    common_erds_count = len(categories['common'])
    energy_erds_count = len(categories['energy'])
    appliance_api_feature_erd_count = 11  # 0x0092-0x0097 and 0x0109-0x010D
    polling_list_max_size = common_erds_count + energy_erds_count + appliance_api_feature_erd_count + max_appliance_erds
    print(f"\nPolling list size check:")
    print(f"  common ERDs: {common_erds_count}, energy ERDs: {energy_erds_count}, appliance API feature ERDs: {appliance_api_feature_erd_count}, max appliance ERDs: {max_appliance_erds}")
    print(f"  POLLING_LIST_MAX_SIZE: {polling_list_max_size}")

    # Generate header (includes POLLING_LIST_MAX_SIZE)
    header_content = generate_header(categories, polling_list_max_size)

    # Write output
    print(f"\nWriting generated header to {output_file}")
    with open(output_file, 'w') as f:
        f.write(header_content)

    # -------------------------------------------------------------------------
    # Generate appliance_api_feature_lists.h from appliance_api.json
    # -------------------------------------------------------------------------
    api_json_file = repo_root / 'lib' / 'public-appliance-api-documentation' / 'appliance_api.json'
    api_output_file = repo_root / 'components' / 'geappliances_bridge' / 'appliance_api_feature_lists.h'

    if not api_json_file.exists():
        print(f"Error: Could not find {api_json_file}", file=sys.stderr)
        print("Make sure git submodules are initialized: git submodule update --init --recursive", file=sys.stderr)
        sys.exit(1)

    print(f"\nReading appliance API definitions from {api_json_file}")
    with open(api_json_file, 'r') as f:
        appliance_api_data = json.load(f)

    feature_apis = appliance_api_data.get('featureApis', {})
    common_features = appliance_api_data.get('common', {})
    valid_feature_apis = [api for api in feature_apis.values() if (api['featureType'] >> 8) <= 9]
    print(f"Found {len(feature_apis)} feature APIs ({len(valid_feature_apis)} within ERDs 0x0093-0x0097 and 0x0109-0x010D)")
    common_ver_count = sum(
        len(vd.get('features', []))
        for vd in common_features.get('versions', {}).values()
    )
    print(f"Found {common_ver_count} common features (ERD 0x0092)")

    api_header_content = generate_appliance_api_feature_lists_header(appliance_api_data)

    print(f"\nWriting generated header to {api_output_file}")
    with open(api_output_file, 'w') as f:
        f.write(api_header_content)

    # -------------------------------------------------------------------------
    # Generate ha_discovery_config.h (minimal - only string ERD list)
    # and per-category JSONL files for runtime fetch
    # -------------------------------------------------------------------------
    ha_output_file = repo_root / 'components' / 'geappliances_bridge' / 'ha_discovery_config.h'

    ha_erds = [e for e in erds if 'ha_domain' in e]
    print(f"\nFound {len(ha_erds)} ERDs with ha_domain metadata for HA MQTT Discovery")

    # Write minimal C header (string ERD list only; full entity data moved to JSONL)
    ha_header_content = generate_ha_discovery_minimal_header(erds)
    print(f"\nWriting minimal ha_discovery_config.h to {ha_output_file}")
    with open(ha_output_file, 'w') as f:
        f.write(ha_header_content)

    # Write per-category JSONL files for runtime download
    jsonl_dir = repo_root / 'ha_discovery'
    jsonl_dir.mkdir(exist_ok=True)
    jsonl_by_cat = generate_ha_discovery_jsonl_by_category(erds)
    total_entries = 0
    for cat, content in jsonl_by_cat.items():
        outfile = jsonl_dir / f'{cat}.jsonl'
        with open(outfile, 'w', encoding='utf-8') as f:
            f.write(content)
        n = content.count('\n')
        total_entries += n
        print(f"  ha_discovery/{cat}.jsonl  ({n} entities, {len(content):,} bytes)")
    print(f"Wrote {len(jsonl_by_cat)} JSONL category files with {total_entries} total entities")

    print("Done!")


if __name__ == '__main__':
    main()
